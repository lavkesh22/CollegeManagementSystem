    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         String studentName = sName.getText();
    String studentClass = sClass.getText();
    String studentRollnumber = sRollnumber.getText();
       try {
        int rollnumber = Integer.parseInt(studentRollnumber.trim());

        Class.forName("com.mysql.cj.jdbc.Driver");
        Connection con = DriverManager.getConnection(
                "jdbc:mysql://127.0.0.1:3306/college", "root", "Lavkesh@123");

        String query = "INSERT INTO students (Rollnumber, studentName, class) VALUES (?,?,?)";
        PreparedStatement pstmt = con.prepareStatement(query);
        pstmt.setInt(1, rollnumber);
        pstmt.setString(2, studentName);
        pstmt.setString(3, studentClass);
        pstmt.executeUpdate();
        
        JOptionPane.showMessageDialog(this, "Student Added Successfully");
        con.close();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter a valid roll number");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

