    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
         String studentRollnumber = sRollnumber.getText();
        DefaultTableModel model = (DefaultTableModel)Table.getModel();
        if(studentRollnumber.isEmpty()){
            JOptionPane.showMessageDialog(this,"Please Enter RollNumber");
        }
       try (Connection con = DriverManager.getConnection(
            "jdbc:mysql://127.0.0.1:3306/college", "root", "Lavkesh@123");
     PreparedStatement pstmt = con.prepareStatement(
            "SELECT * FROM students WHERE Rollnumber = ?")) {

    pstmt.setString(1, studentRollnumber);   // use setInt(1, Integer.parseInt(studentRollnumber)) if the column is INT

    try (ResultSet rs = pstmt.executeQuery()) {
        model.setRowCount(0);                // clear old results
        while (rs.next()) {
            String rollNumber   = String.valueOf(rs.getInt("Rollnumber"));
            String studentName  = rs.getString("StudentName");
            String studentClass = rs.getString("class");

            model.addRow(new String[]{rollNumber, studentName, studentClass});
        }
    }
    if (model.getRowCount() == 0) {
    JOptionPane.showMessageDialog(this, "No Result Found");
}
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
         
           
        
    }//GEN-LAST:event_jButton2ActionPerformed

